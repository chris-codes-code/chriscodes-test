const px = (value) => `${value}px`;

const getCappedVwPx = (length, contentWidthMax) => (contentWidthMax * length.value) / 100;

/** Outer container at max = content max + capped gutters on both sides. */
const getMaxContainerWidthPx = (contentWidthMax, gutter) => {
	if (gutter.unit === 'vw') {
		return Math.round(contentWidthMax + getCappedVwPx(gutter, contentWidthMax) * 2);
	}

	return contentWidthMax + gutter.value * 2;
};

/** Raw length from config — keeps growing with vw when used as-is. */
const toFluidLengthCss = (length) => length.css;

/**
 * Default length used by the layout. vw values freeze at content-width-max
 * and scale with the container so they shrink in step with container-width-max.
 */
const toCappedLengthCss = (length) => {
	if (length.unit !== 'vw') return length.css;

	const capped = `var(--content-width-max) / 100 * ${length.value}`;

	return `calc(${capped} * min(1, 100vw / var(--container-width-max)))`;
};

